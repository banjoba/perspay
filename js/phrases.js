const lastPick = {};

export function pickTemplate(key) {
  const pool = PHRASES[key] || PHRASES.ok;
  let idx = Math.floor(Math.random() * pool.length);
  if (pool.length > 1 && idx === lastPick[key]) idx = (idx + 1) % pool.length;
  lastPick[key] = idx;
  return pool[idx];
}

export function fillTemplate(template, vars = {}) {
  const text = template.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '');
  return text.charAt(0).toUpperCase() + text.slice(1);
}

export function pickPhrase(key, vars = {}) {
  return fillTemplate(pickTemplate(key), vars);
}
