"""Tiny sync endpoint for the Persik PWA and its Scriptable widget.

PUT|POST /persik/<token>      -> store the JSON body for that token (POST for sendBeacon/keepalive)
GET /persik/<token>           -> return the stored JSON (404 if none)
POST /persik/<token>/feed     -> append a feeding "now" if the minimum gap from settings has passed
Token is a 24-64 char hex string generated by the app; it is both id and secret.
"""
import json
import os
import re
import sys
import time
from datetime import datetime
from zoneinfo import ZoneInfo
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

DATA_DIR = Path(os.environ.get("PERSIK_DATA", "/var/lib/persik-sync"))
PORT = int(os.environ.get("PERSIK_PORT", "8890"))
ALLOWED_ORIGIN = os.environ.get("PERSIK_ORIGIN", "https://banjoba.github.io")
MAX_BODY = 512 * 1024
PATH_RE = re.compile(r"^/persik/([a-f0-9]{24,64})(/feed)?$")
TZ = ZoneInfo(os.environ.get("PERSIK_TZ", "Europe/Moscow"))
DEFAULT_SETTINGS = {"minGapMin": 120, "dueGapMin": 180, "urgentGapMin": 240}


def format_minutes(minutes):
    hours, rest = divmod(int(minutes), 60)
    if hours and rest:
        return f"{hours} ч {rest} мин"
    return f"{hours} ч" if hours else f"{rest} мин"


class Handler(BaseHTTPRequestHandler):
    server_version = "persik-sync/1.0"

    def log_message(self, fmt, *args):
        sys.stderr.write("%s %s\n" % (self.address_string(), fmt % args))

    def _cors(self):
        self.send_header("Access-Control-Allow-Origin", ALLOWED_ORIGIN)
        self.send_header("Access-Control-Allow-Methods", "GET, PUT, POST, OPTIONS")
        self.send_header("Access-Control-Allow-Headers", "Content-Type")
        self.send_header("Access-Control-Max-Age", "86400")
        self.send_header("Cache-Control", "no-store")

    def _reply(self, status, payload):
        body = json.dumps(payload, ensure_ascii=False).encode("utf-8")
        self.send_response(status)
        self._cors()
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def _route(self):
        match = PATH_RE.match(self.path.split("?", 1)[0])
        if not match:
            return None, None
        return match.group(1), ("feed" if match.group(2) else "state")

    def _token(self):
        token, action = self._route()
        return token if action == "state" else None

    def do_OPTIONS(self):
        self.send_response(204)
        self._cors()
        self.end_headers()

    def do_GET(self):
        token = self._token()
        if not token:
            return self._reply(404, {"error": "not found"})
        path = DATA_DIR / f"{token}.json"
        if not path.exists():
            return self._reply(404, {"error": "no data"})
        self.send_response(200)
        self._cors()
        self.send_header("Content-Type", "application/json; charset=utf-8")
        body = path.read_bytes()
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_PUT(self):
        token, action = self._route()
        if token and action == "feed":
            return self._feed(token)
        if not token:
            return self._reply(404, {"error": "not found"})
        length = int(self.headers.get("Content-Length") or 0)
        if length <= 0 or length > MAX_BODY:
            return self._reply(413, {"error": "bad size"})
        raw = self.rfile.read(length)
        try:
            data = json.loads(raw)
            if not isinstance(data, dict) or not isinstance(data.get("feedings"), list):
                raise ValueError("shape")
        except (ValueError, UnicodeDecodeError):
            return self._reply(400, {"error": "bad json"})
        DATA_DIR.mkdir(parents=True, exist_ok=True)
        tmp = DATA_DIR / f"{token}.json.tmp"
        tmp.write_bytes(raw)
        tmp.replace(DATA_DIR / f"{token}.json")
        self._reply(200, {"ok": True, "feedings": len(data["feedings"])})

    do_POST = do_PUT

    def _feed(self, token):
        path = DATA_DIR / f"{token}.json"
        if not path.exists():
            return self._reply(404, {"ok": False, "message": "По этому коду дневника нет"})
        data = json.loads(path.read_bytes())
        settings = {**DEFAULT_SETTINGS, **(data.get("settings") or {})}
        feedings = [f for f in data.get("feedings") or [] if isinstance(f, dict) and isinstance(f.get("at"), (int, float))]
        now_ms = int(time.time() * 1000)
        past = [f["at"] for f in feedings if f["at"] <= now_ms]
        minutes = None if not past else (now_ms - max(past)) // 60000
        if minutes is not None and minutes < settings["minGapMin"]:
            message = f"Рано: с кормления прошло всего {format_minutes(minutes)}"
            return self._reply(200, {"ok": False, "message": message, "minutes": minutes})
        feedings.append({"id": f"w-{now_ms:x}", "at": now_ms, "note": "с виджета"})
        data["feedings"] = sorted(feedings, key=lambda f: f["at"])
        tmp = DATA_DIR / f"{token}.json.tmp"
        tmp.write_text(json.dumps(data, ensure_ascii=False))
        tmp.replace(path)
        clock = datetime.fromtimestamp(now_ms / 1000, TZ).strftime("%H:%M")
        return self._reply(200, {"ok": True, "message": f"Ням! Персик покормлен в {clock}", "at": now_ms})


if __name__ == "__main__":
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    ThreadingHTTPServer(("127.0.0.1", PORT), Handler).serve_forever()
